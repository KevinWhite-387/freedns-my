<?php
declare(strict_types=1);

/**
 * freedns.my - back office: the cron key (the shared secret of the scheduled tasks).
 *
 * Written because the key is easy to lose: it lives in one row of the settings table, it is not printed
 * anywhere else, and three scheduled tasks depend on it. This page shows it, can generate a new one, and
 * prints the three ready-to-paste commands with the current key already filled in - so nothing has to be
 * assembled by hand.
 *
 * Owner only. The back office is English-only, like the rest of it.
 */

require dirname(__DIR__) . '/inc/bootstrap.php';

$admin  = require_admin();
require_owner('The cron key');
$errors = [];
$fresh  = '';

if ($_SERVER['REQUEST_METHOD'] === 'POST') {
    csrf_verify();
    $action = strtolower((string)($_POST['action'] ?? ''));

    if ($action === 'generate') {
        $new = bin2hex(random_bytes(32));
        set_setting('cf_cron_key', $new);
        $fresh = $new;
        log_action('cron_key_new', 'settings', null,
            'a new cron key was generated by ' . (string)$admin['username'] . ' (the scheduled tasks must be updated)');
        flash('A new key was generated. Update the three scheduled tasks below - until then they answer "forbidden".', 'ok');
    }
}

$key   = trim((string)setting('cf_cron_key', ''));
$base  = rtrim(app_base_url(), '/');
$tasks = [
    ['DNS reconcile (records are pushed to the providers)', $base . '/admin/dns-cron.php?key=' . $key],
    ['Watchdog (published records + cloud server expiry)', $base . '/alert-cron.php?key=' . $key . '&limit=25'],
    ['Mail pipeline (fetch, archive, check, forward)', $base . '/mail-cron.php?key=' . $key . '&limit=20'],
];

page_header('Cron key');
?>
<p>
One key is shared by every scheduled task: it is the only thing that tells the site "this request really
comes from my own cron, not from a stranger". Losing it is not a problem - it can be generated again here -
but the scheduled tasks have to be updated afterwards, otherwise they answer <code>forbidden</code> and
quietly stop working.
</p>
<?= error_list($errors) ?>

<h2>The key in use</h2>
<?php if ($key === ''): ?>
<div class="msg error">No key is set, so every scheduled task is refused. Generate one below.</div>
<?php else: ?>
<p><code style="font-size:1.2em;word-break:break-all"><?= h($key) ?></code></p>
<p class="hint">
It is stored in the database as the row
<code>settings.name = 'cf_cron_key'</code> (database <code><?= h((string)db_value('SELECT DATABASE()', [], '')) ?></code>,
table <code>settings</code>) if you ever want to look at it from phpMyAdmin.
<strong>Do not paste it anywhere public</strong> - anybody who has it can trigger these three tasks.
</p>
<?php endif; ?>

<h2>The three scheduled tasks</h2>
<p class="hint">Copy each line into aaPanel &rarr; Cron &rarr; add a Shell script task. One a minute is fine for all three.</p>
<table>
  <tr><th>What it does</th><th>Command</th></tr>
  <?php foreach ($tasks as $task): ?>
  <tr>
    <td><?= h($task[0]) ?></td>
    <td><code style="word-break:break-all">curl -s "<?= h($task[1]) ?>" <?= $task[0][0] === 'M'
        ? '>> /www/wwwlogs/freedns-mail.log 2>&1' : '>/dev/null 2>&1' ?></code></td>
  </tr>
  <?php endforeach; ?>
</table>

<h2>Check them by hand</h2>
<p class="hint">Run these on the server. A working task answers with its own report; a wrong key answers
<code>forbidden</code>; an empty key answers <code>no cron key is set</code>.</p>
<?php foreach ($tasks as $task): ?>
<p><code style="word-break:break-all">curl -s "<?= h($task[1]) ?>" | head -5</code></p>
<?php endforeach; ?>

<h2>Generate a new key</h2>
<p>
Do this if the key leaked, or if you simply want a fresh start. <strong>Every scheduled task has to be
updated in the same minute</strong>, so keep this page open while you do it.
</p>
<form method="post" action="cron-key.php">
  <?= csrf_field() ?>
  <input type="hidden" name="action" value="generate">
  <p><input type="submit" value="Generate a new key"></p>
</form>
<?php if ($fresh !== ''): ?>
<div class="msg ok">
  The new key is <code style="word-break:break-all"><?= h($fresh) ?></code> - the commands above already use
  it. Replace the old ones in aaPanel now.
</div>
<?php endif; ?>
<?php
page_footer();
