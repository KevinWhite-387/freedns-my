/* PHP 7.4 compatibility. inc/functions.php declares the same polyfills, but the installer
   uses these functions before that file is loaded. */
if (!function_exists('str_starts_with')) {
    function str_starts_with(string $haystack, string $needle): bool
    {
        return $needle === '' || strncmp($haystack, $needle, strlen($needle)) === 0;
    }
}
if (!function_exists('str_ends_with')) {
    function str_ends_with(string $haystack, string $needle): bool
    {
        return $needle === '' || substr($haystack, -strlen($needle)) === $needle;
    }
}
if (!function_exists('str_contains')) {
    function str_contains(string $haystack, string $needle): bool
    {
        return $needle === '' || strpos($haystack, $needle) !== false;
    }
}

define('INS_ROOT', __DIR__);
$configPath = INS_ROOT . '/inc/config.php';

session_start();

// The installer writes inc/config.php and creates the owner account, so the form carries a token.
if (empty($_SESSION['ins_token'])) {
    $_SESSION['ins_token'] = bin2hex(random_bytes(32));
}

/* ------------------------------------------------------------------ *
 * Small standalone helpers (the application itself is not loaded yet) *
 * ------------------------------------------------------------------ */

function ins_h($value): string
{
    return htmlspecialchars((string)$value, ENT_QUOTES | ENT_SUBSTITUTE, 'UTF-8');
}

function ins_field(): string
{
    return '<input type="hidden" name="ins_token" value="' . ins_h((string)$_SESSION['ins_token']) . '">';
}

function ins_post(string $key, string $default = ''): string
{
    return trim((string)($_POST[$key] ?? $default));
}

function ins_detect_base_url(): string
{
    $https  = (!empty($_SERVER['HTTPS']) && strtolower((string)$_SERVER['HTTPS']) !== 'off')
        || (string)($_SERVER['SERVER_PORT'] ?? '') === '443';
    $host   = (string)($_SERVER['HTTP_HOST'] ?? 'localhost');
    $script = str_replace('\\', '/', (string)($_SERVER['SCRIPT_NAME'] ?? '/install.php'));
    $dir    = rtrim(str_replace('\\', '/', dirname($script)), '/');
    if (basename($dir) === 'admin') {
        $dir = rtrim(dirname($dir), '/');
    }

    return ($https ? 'https' : 'http') . '://' . $host . $dir;
}

/** Splits a .sql file into single statements (no procedural code in our schema). */
function ins_split_sql(string $sql): array
{
    $statements = [];
    $current    = '';
    foreach (preg_split('/\r?\n/', $sql) ?: [] as $line) {
        $trimmed = trim($line);
        if ($trimmed === '' || str_starts_with($trimmed, '--') || str_starts_with($trimmed, '#')) {
            continue;
        }
        $current .= $line . "\n";
        if (str_ends_with(rtrim($trimmed), ';')) {
            $statements[] = rtrim(trim($current), ';');
            $current      = '';
        }
    }
    if (trim($current) !== '') {
        $statements[] = trim($current);
    }

    return $statements;
}

function ins_config_contents(array $cfg): string
{
    return "<?php\n"
        . "// freedns.my configuration - generated by install.php on " . date('c') . "\n"
        . "// Keep this file private: it contains the database password.\n\n"
        . 'return ' . var_export($cfg, true) . ";\n";
}

