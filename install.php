/* ------------------------------------------------------------------ *
 * Requirements                                                        *
 * ------------------------------------------------------------------ */

$requirements = [
    'PHP 7.4 or newer' => version_compare(PHP_VERSION, '7.4.0', '>='),
    'PDO extension'    => extension_loaded('pdo'),
    'pdo_mysql driver' => extension_loaded('pdo_mysql'),
];
$requirementsOk = !in_array(false, $requirements, true);

/* ------------------------------------------------------------------ *
 * Already installed? Or an existing configuration to reuse?           *
 * ------------------------------------------------------------------ */

$alreadyInstalled = false;
$installedError   = '';
$lockedConfig     = null;

if (is_file($configPath)) {
    try {
        $existing = require $configPath;
        if (is_array($existing) && isset($existing['db']) && is_array($existing['db'])
            && (string)($existing['db']['name'] ?? '') !== '') {
            // The file exists and looks usable: keep its database settings, and never rewrite
            // the file from form input. This is the "reset the administrator account" path.
            $lockedConfig = $existing;
        } else {
            $installedError = 'inc/config.php exists but does not contain a freedns.my configuration.';
        }
    } catch (Throwable $e) {
        $installedError = 'inc/config.php could not be read: ' . $e->getMessage();
    }
}

if ($lockedConfig !== null) {
    try {
        $c   = $lockedConfig['db'];
        $dsn = sprintf(
            'mysql:host=%s;port=%d;dbname=%s;charset=utf8mb4',
            (string)($c['host'] ?? ''),
            (int)($c['port'] ?? 3306),
            (string)($c['name'] ?? '')
        );
        $testPdo = new PDO($dsn, (string)($c['user'] ?? ''), (string)($c['pass'] ?? ''), [
            PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION,
        ]);
        $count = (int)$testPdo->query('SELECT COUNT(*) FROM admins')->fetchColumn();
        if ($count > 0) {
            $alreadyInstalled = true;
        }
    } catch (Throwable $e) {
        $installedError = 'The database from inc/config.php could not be opened: ' . $e->getMessage();
    }
}

if ($alreadyInstalled) {
    ins_page('Already installed', '<div class="box"><p class="bad"><strong>This application is already installed.</strong></p>'
        . '<p>An administrator account exists in the database.</p>'
        . '<p>Delete <code>install.php</code> from the site directory and sign in at '
        . '<a href="admin/login.php">admin/login.php</a>.</p></div>');
    exit;
}

/* ------------------------------------------------------------------ *
 * Handle the submission                                               *
 * ------------------------------------------------------------------ */

$errors  = [];
$success = false;
$manualConfig = '';
$baseUrlDefault = ins_detect_base_url();
$effectiveBaseUrl = $baseUrlDefault;

$defaults = [
    'db_host'    => '127.0.0.1',
    'db_port'    => '3306',
    'db_name'    => 'freedns',
    'db_user'    => 'freedns',
    'db_pass'    => '',
    'base_url'   => $baseUrlDefault,
    'zone_name'  => 'freedns.my',
    'site_title' => 'freedns.my',
    'admin_user' => 'admin',
    'admin_mail' => '',
    'contact'    => '',
];

if ($lockedConfig !== null) {
    // Recovery mode: the connection details come from the existing file, not from the form.
    $defaults['db_host'] = (string)($lockedConfig['db']['host'] ?? '');
    $defaults['db_port'] = (string)($lockedConfig['db']['port'] ?? 3306);
    $defaults['db_name'] = (string)($lockedConfig['db']['name'] ?? '');
    $defaults['db_user'] = (string)($lockedConfig['db']['user'] ?? '');
    $defaults['db_pass'] = (string)($lockedConfig['db']['pass'] ?? '');
    $defaults['base_url'] = (string)($lockedConfig['site']['base_url'] ?? '');
}

if ($_SERVER['REQUEST_METHOD'] === 'POST') {
    $in = [];
    foreach (array_keys($defaults) as $key) {
        $in[$key] = ins_post($key, (string)$defaults[$key]);
    }
    $adminPass     = (string)($_POST['admin_pass'] ?? '');
    $adminPass2    = (string)($_POST['admin_pass2'] ?? '');
    $effectiveBaseUrl = $in['base_url'] !== '' ? $in['base_url'] : $baseUrlDefault;

    $token = (string)($_POST['ins_token'] ?? '');
    if ($token === '' || !hash_equals((string)$_SESSION['ins_token'], $token)) {
        $errors[] = 'This form has expired. Please reload the page and fill it in again.';
    }

    if (!$requirementsOk) {
        $errors[] = 'The required PHP extensions are missing, so the installation cannot start.';
    }

    if ($lockedConfig === null) {
        if ($in['db_host'] === '')  { $errors[] = 'Database host is required.'; }
        if ($in['db_name'] === '')  { $errors[] = 'Database name is required.'; }
        if ($in['db_user'] === '')  { $errors[] = 'Database user is required.'; }
        if ($in['db_name'] !== '' && !preg_match('/^[A-Za-z0-9_$-]+$/', $in['db_name'])) {
            $errors[] = 'The database name may contain only letters, digits, the underscore and the hyphen.';
        }
        if (!ctype_digit($in['db_port']) || (int)$in['db_port'] < 1 || (int)$in['db_port'] > 65535) {
            $errors[] = 'Database port must be a number between 1 and 65535.';
        }
    }
    if (!preg_match('/^[a-z0-9]([a-z0-9-]*[a-z0-9])?(\.[a-z0-9]([a-z0-9-]*[a-z0-9])?)+$/', strtolower($in['zone_name']))) {
        $errors[] = 'The zone name must look like a domain name, for example freedns.my.';
    }
    if ($in['admin_user'] === '' || !preg_match('/^[A-Za-z0-9._-]{3,32}$/', $in['admin_user'])) {
        $errors[] = 'The administrator user name must be 3 to 32 characters (letters, digits, dot, dash, underscore).';
    }
    if (strlen($adminPass) < 10) {
        $errors[] = 'The administrator password must be at least 10 characters long.';
    }
    if ($adminPass !== $adminPass2) {
        $errors[] = 'The two administrator passwords do not match.';
    }
    if ($in['admin_mail'] !== '' && !filter_var($in['admin_mail'], FILTER_VALIDATE_EMAIL)) {
        $errors[] = 'The administrator e-mail address is not valid.';
    }
    if ($in['base_url'] !== '' && !preg_match('#^https?://#i', $in['base_url'])) {
        $errors[] = 'The site URL must start with http:// or https:// (or be left empty for auto-detection).';
    }

    $pdo = null;
    if ($errors === []) {
        try {
            $serverDsn = sprintf('mysql:host=%s;port=%d;charset=utf8mb4', $in['db_host'], (int)$in['db_port']);
            $serverPdo = new PDO($serverDsn, $in['db_user'], $in['db_pass'], [
                PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION,
            ]);
            $safeName = str_replace('`', '', $in['db_name']);
            $serverPdo->exec(
                'CREATE DATABASE IF NOT EXISTS `' . $safeName . '` DEFAULT CHARACTER SET utf8mb4 '
                . 'COLLATE utf8mb4_unicode_ci'
            );

            $dsn = sprintf(
                'mysql:host=%s;port=%d;dbname=%s;charset=utf8mb4',
                $in['db_host'],
                (int)$in['db_port'],
                $safeName
            );
            $pdo = new PDO($dsn, $in['db_user'], $in['db_pass'], [
                PDO::ATTR_ERRMODE            => PDO::ERRMODE_EXCEPTION,
                PDO::ATTR_DEFAULT_FETCH_MODE => PDO::FETCH_ASSOC,
                PDO::ATTR_EMULATE_PREPARES   => false,
            ]);
        } catch (PDOException $e) {
            $errors[] = 'Could not connect to MySQL: ' . $e->getMessage()
                . ' — in aaPanel open Databases, create the database and make sure the database user '
                . 'has all privileges on it (or use root).';
        }
    }

    if ($errors === [] && $pdo instanceof PDO) {
        try {
            $schemaFile = INS_ROOT . '/schema.sql';
            if (!is_file($schemaFile)) {
                throw new RuntimeException('schema.sql is missing from the site directory.');
            }
            foreach (ins_split_sql((string)file_get_contents($schemaFile)) as $statement) {
                $pdo->exec($statement);
            }
        } catch (Throwable $e) {
            $errors[] = 'Could not create the database tables: ' . $e->getMessage();
        }
    }

    $config = [
        'db' => [
            'host'    => $in['db_host'],
            'port'    => (int)$in['db_port'],
            'name'    => $in['db_name'],
            'user'    => $in['db_user'],
            'pass'    => $in['db_pass'],
            'charset' => 'utf8mb4',
        ],
        'site' => [
            'base_url'     => $effectiveBaseUrl,
            'session_name' => 'freednssid',
            'timezone'     => 'UTC',
            'debug'        => false,
        ],
        'security' => [
            'cookie_secure'        => str_starts_with(strtolower($effectiveBaseUrl), 'https://'),
            'login_max_attempts'   => 8,
            'login_window_minutes' => 15,
        ],
    ];

    $configWritten = false;
    if ($errors === []) {
        if ($lockedConfig !== null) {
            // Keep the existing inc/config.php exactly as it is.
            $configWritten = true;
        } else {
            $contents = ins_config_contents($config);
            if (@file_put_contents($configPath, $contents) !== false) {
                @chmod($configPath, 0640);
                $configWritten = true;
            } else {
                $manualConfig = $contents;
                $errors[]     = 'The database and the tables are ready, but inc/config.php could not be '
                    . 'written (the inc/ directory is not writable). Create the file manually with the '
                    . 'contents shown below, then delete install.php.';
            }
        }
    }

    if ($errors === [] && $configWritten) {
        try {
            $GLOBALS['FD_CONFIG'] = $config;
            define('FD_ROOT', INS_ROOT);
            define('FD_INC', INS_ROOT . '/inc');
            require INS_ROOT . '/inc/db.php';
            require INS_ROOT . '/inc/functions.php';

            $pdo->query('SELECT 1 FROM settings LIMIT 1');

            $seed = default_settings();
            $seed['site_title']    = $in['site_title'] !== '' ? $in['site_title'] : $in['zone_name'];
            $seed['contact_email'] = $in['contact'] !== '' ? $in['contact'] : 'hostmaster@' . strtolower($in['zone_name']);

            $stmt = $pdo->prepare(
                $lockedConfig !== null
                    ? 'INSERT IGNORE INTO settings (setting_key, setting_value, updated_at) VALUES (?, ?, NOW())'
                    : 'INSERT INTO settings (setting_key, setting_value, updated_at) VALUES (?, ?, NOW())
                       ON DUPLICATE KEY UPDATE setting_value = VALUES(setting_value), updated_at = NOW()'
            );
            foreach ($seed as $key => $value) {
                $stmt->execute([(string)$key, (string)$value]);
            }

            // The first zone: more can be added later under Administration -> Zones.
            $zoneName = strtolower(trim((string)$in['zone_name']));
            $existingZone = $pdo->prepare('SELECT id FROM zones WHERE name = ?');
            $existingZone->execute([$zoneName]);
            if ($existingZone->fetchColumn() === false) {
                $pdo->prepare(
                    'INSERT INTO zones (name, title, description, is_open, allow_subdomains,
                        max_domains_per_email, sort_order, created_at, updated_at)
                     VALUES (?, ?, ?, 1, 1, 0, 10, NOW(), NOW())'
                )->execute([$zoneName, $zoneName, '']);
            }

            $stmt = $pdo->prepare(
                'INSERT INTO admins (username, password_hash, email, is_owner, created_at) VALUES (?, ?, ?, 1, NOW())'
            );
            $stmt->execute([
                $in['admin_user'],
                password_hash($adminPass, PASSWORD_DEFAULT),
                $in['admin_mail'] === '' ? null : $in['admin_mail'],
            ]);

            $success = true;
        } catch (Throwable $e) {
            $errors[] = 'The tables were created but the initial data could not be written: ' . $e->getMessage();
        }
    } elseif ($errors === [] && !$configWritten) {
        $errors[] = 'The database is ready, but inc/config.php could not be written. '
            . 'Create the file manually with the contents shown below and then delete install.php.';
    }
}

/* ------------------------------------------------------------------ *
 * Output                                                              *
 * ------------------------------------------------------------------ */

if ($success) {
    $loginUrl = rtrim($effectiveBaseUrl, '/') . '/admin/login.php';
    ins_page('Installation complete', '<div class="box">'
        . '<p class="ok"><strong>Installation complete.</strong></p>'
        . '<p>The database tables are in place and the administrator account '
        . '<code>' . ins_h((string)($_POST['admin_user'] ?? '')) . '</code> has been created.</p>'
        . '<p><strong>Delete install.php from the site directory now.</strong> '
        . 'It is the only step that cannot be undone afterwards.</p>'
        . '<p>Then sign in at <a href="' . ins_h($loginUrl) . '">' . ins_h($loginUrl) . '</a> '
        . 'and open <em>Settings</em> to review the announcement, the policy text and the limits, and '
        . '<em>Zones</em> to add further suffixes (for example asia.ci).</p>'
        . '</div>');
    exit;
}

$body = '';
if (!$requirementsOk) {
    $body .= '<div class="box"><p class="bad"><strong>Missing requirements</strong></p><table>';
    foreach ($requirements as $label => $ok) {
        $body .= '<tr><td>' . ins_h($label) . '</td><td class="' . ($ok ? 'ok' : 'bad') . '">'
            . ($ok ? 'yes' : 'no') . '</td></tr>';
    }
    $body .= '</table><p>Install or enable the missing PHP extensions in aaPanel (App Store &rarr; PHP &rarr; '
        . 'Settings &rarr; Install extensions), then reload this page.</p></div>';
}
if ($installedError !== '') {
    $body .= '<div class="box"><p class="bad">' . ins_h($installedError) . '</p></div>';
}
if ($errors !== []) {
    $body .= '<div class="box"><p class="bad"><strong>Please correct the following:</strong></p><ul>';
    foreach ($errors as $error) {
        $body .= '<li>' . ins_h($error) . '</li>';
    }
    $body .= '</ul></div>';
}
if ($manualConfig !== '') {
    $body .= '<div class="box"><p>Create <code>inc/config.php</code> with exactly this content '
        . '(and remove the write-protection afterwards):</p><pre>' . ins_h($manualConfig) . '</pre></div>';
}

if ($lockedConfig !== null) {
    $body .= '<div class="box"><p><strong>Recovery mode.</strong> <code>inc/config.php</code> already exists, '
        . 'so the database connection is taken from that file and cannot be changed with this form. Only the '
        . 'first administrator account will be created again.</p><p>Database in use: <code>'
        . ins_h((string)($lockedConfig['db']['name'] ?? '')) . '</code> on <code>'
        . ins_h((string)($lockedConfig['db']['host'] ?? '')) . '</code>.</p>'
        . '<p class="hint">To point the site at a different database, delete <code>inc/config.php</code> '
        . 'first &mdash; and only do that if you really mean it.</p></div>';
} else {
    $body .= '<p>This wizard creates the database tables, writes <code>inc/config.php</code> and adds the first '
        . 'administrator account. Nothing else on the server is touched.</p>';
}

$body .= '<form method="post" action="install.php">' . ins_field();

if ($lockedConfig === null) {
    $body .= '<h2>1. Database (MySQL / MariaDB)</h2>';
    foreach ([
        'db_host' => 'Database host',
        'db_port' => 'Database port',
        'db_name' => 'Database name',
        'db_user' => 'Database user',
        'db_pass' => 'Database password',
    ] as $key => $label) {
        $type = $key === 'db_pass' ? 'password' : 'text';
        $body .= '<label for="' . $key . '">' . ins_h($label) . '</label>'
            . '<input type="' . $type . '" id="' . $key . '" name="' . $key . '" value="'
            . ins_h((string)($_POST[$key] ?? $defaults[$key])) . '">';
    }
    $body .= '<p class="hint">In aaPanel create the database first (Databases &rarr; Add database) and use the '
        . 'user and password shown there. The database is created automatically if it does not exist yet.</p>';
}

$body .= '<h2>' . ($lockedConfig === null ? '2' : '1') . '. Site</h2>';
$body .= '<label for="base_url">Public base URL</label><input type="text" id="base_url" name="base_url" value="'
    . ins_h((string)($_POST['base_url'] ?? $defaults['base_url'])) . '">';
$body .= '<p class="hint">Used for links in e-mails. Leave as detected if the site answers on this address.</p>';
$body .= '<label for="site_title">Site title</label><input type="text" id="site_title" name="site_title" value="'
    . ins_h((string)($_POST['site_title'] ?? $defaults['site_title'])) . '">';
$body .= '<label for="zone_name">First zone (the suffix you hand names out under)</label>'
    . '<input type="text" id="zone_name" name="zone_name" value="'
    . ins_h((string)($_POST['zone_name'] ?? $defaults['zone_name'])) . '">';
$body .= '<p class="hint">For example <code>freedns.my</code>. Further zones such as <code>asia.ci</code> '
    . 'are added later under <em>Administration &rarr; Zones</em>. Each zone has to be hosted in DNS by '
    . 'you, and the exported records are pasted there.</p>';
$body .= '<label for="contact">Public contact e-mail (optional)</label>'
    . '<input type="text" id="contact" name="contact" value="'
    . ins_h((string)($_POST['contact'] ?? $defaults['contact'])) . '">';

$body .= '<h2>' . ($lockedConfig === null ? '3' : '2') . '. Administrator account</h2>';
$body .= '<label for="admin_user">User name</label><input type="text" id="admin_user" name="admin_user" value="'
    . ins_h((string)($_POST['admin_user'] ?? $defaults['admin_user'])) . '">';
$body .= '<label for="admin_mail">E-mail (optional)</label><input type="text" id="admin_mail" name="admin_mail" value="'
    . ins_h((string)($_POST['admin_mail'] ?? $defaults['admin_mail'])) . '">';
