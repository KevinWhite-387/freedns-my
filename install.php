        . "hr{border:0;border-top:1px solid #bbb;margin:1em 0}"
        . "input[type=text],input[type=password]{font-family:inherit;font-size:inherit;width:100%;"
        . "max-width:32em;padding:.3em;border:1px solid #999}"
        . "input[type=submit]{font-family:inherit;font-size:inherit;padding:.35em .9em;border:1px solid #666;background:#f2f2f2}"
        . "label{display:block;margin:.8em 0 .15em}table{border-collapse:collapse}"
